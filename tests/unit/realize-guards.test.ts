import { describe, expect, it } from 'vitest';
import { lotsDownOf } from '../../src/server/rebalanceRunner';

describe('lotsDownOf', () => {
  it.each([
    [0.0499999, '0.001', 49],
    [1.6669999, '0.001', 1_666],
    [2_000.0009999, '0.001', 2_000_000],
    [1_999.9999999, '0.001', 1_999_999],
    [66.6659999, '0.00001', 6_666_599],
    [66.66599999999, '0.00001', 6_666_599],
    [2_000, '0.0001', 20_000_000],
    [2_000.00019999, '0.0001', 20_000_001],
    [0.1 + 0.2, '0.1', 3],
    [0.7 - 0.4, '0.1', 3],
    [4.03 - 0.36, '0.0001', 36_700],
    [0, '0.0001', 0],
  ])('%d at a lot of %s is %d whole lots', (qty, lot, lots) => {
    expect(lotsDownOf(qty, lot)).toBe(lots);
  });
});
