export function perp(symbol: string, qty: number, entry: number, mark: number): RealizePerp {
  return {
    symbol,
    positionQty: String(qty),
    entryPrice: String(entry),
    markPrice: String(mark),
    initialMargin: String(Math.abs(qty) * mark * IM_RATE),
  };
}

interface Wallet {
  cash: number;
  upnl: number;
}

export interface BookSpec {
  usdt: Wallet;
  usdc: Wallet;
  availableMargin: number;
  perps: RealizePerp[];
  books: Record<string, NormalizedBook | null>;
  notionalUsd: number;
}

export interface RealizeBook {
  spec: BookSpec;
  account: AccountLike;
  buckets: Bucket[];
  inputs: PlanInputs;
}

function walletAsset(coin: string, venue: string, wallet: Wallet): AssetLike {
  const borrow = Math.max(0, -wallet.cash);
  return {
    coin,
    exchangeType: venue,
    balance: String(wallet.cash),
    availableBalance: String(Math.max(0, wallet.cash)),
    upnl: String(wallet.upnl),
    equity: String(wallet.cash + wallet.upnl),
    liability: String(borrow),
    borrowingInitialMargin: String(borrow * 0.2),
    borrowingMaintenanceMargin: String(borrow * 0.1),
  };
}

export function realizeBook(spec: BookSpec): RealizeBook {
  const marginBalance = spec.usdt.cash + spec.usdt.upnl + spec.usdc.cash + spec.usdc.upnl;
  const account: AccountLike = {
    availableMargin: String(spec.availableMargin),
    marginBalance: String(marginBalance),
    initialMargin: String(marginBalance - spec.availableMargin),
    assets: [
      walletAsset('USDT', 'CROSSEX', spec.usdt),
      walletAsset('USDC', 'HYPERLIQUID', spec.usdc),
      walletAsset('USDC', 'GATE', { cash: 0, upnl: 0 }),
    ],
  };
  return {
    spec,
    account,
    buckets: bucketsFrom(account, RATES, {}),
    inputs: {
      coins: [{ coin: 'USDC', minTransAmount: 11, estFee: 1, isDisabled: 0 }],
      spotRule: { state: 'live' },
      spotTakerRate: 0,
      ask: 1.0001,
      bid: 0.9999,
      notional: { 'USDT/CROSSEX': spec.notionalUsd, 'USDC/HYPERLIQUID': spec.notionalUsd },
      perps: spec.perps,
      books: spec.books,
      feeRows: FEE_ROWS,
      perpRules: PERP_RULES,
      availableMargin: spec.availableMargin,
    },
  };
}

