function valueOf(name: string, raw: string): string {
  if (name === 'inner') return localizeServerText(raw);
  const word = name.endsWith('Word') ? WORDS[raw] : undefined;
  return word ? t(`errors.word.${word}`) : raw;
}

// The rule table checks each key; one call site cannot narrow every key's placeholder types.
const byKey = t as unknown as (key: string, values: Record<string, string>) => string;

function matchWhole(text: string): string | null {
  for (const [re, key, names = []] of RULES) {
    const m = re.exec(text);
    if (m) return byKey(`errors.${key}`, Object.fromEntries(names.map((name, i) => [name, valueOf(name, m[i + 1] ?? '')])));
  }
  return null;
}

function join(first: string, rest: string): string {
  return /[.!?]$/.test(first) ? t('errors.sentencesSpaced', { first, rest }) : t('errors.sentences', { first, rest });
}

function translate(text: string): string | null {
  const whole = matchWhole(text);
  if (whole !== null) return whole;
  const ends = Array.from(text.matchAll(/[.!?] (?=\S)/g), (split) => (split.index ?? 0) + 1);
  for (const end of ends) {
    const head = matchWhole(text.slice(0, end));
    if (head !== null) return join(head, localizeServerText(text.slice(end + 1)));
  }
  if (ends.length === 0) return null;
  const tail = translate(text.slice(ends[0] + 1));
  return tail === null ? null : join(text.slice(0, ends[0]), tail);
}

export function localizeServerText(text: string): string {
  // A malformed envelope (a proxy's bare-string error) carries no message; translating must never throw.
  if (typeof text !== 'string') return text;
  return translate(text) ?? text;
}

export function localizeServerError<T extends { message: string; hint?: string }>(e: T): T {
  return { ...e, message: localizeServerText(e.message), ...(e.hint === undefined ? {} : { hint: localizeServerText(e.hint) }) };
}
