describe('localizeServerText in English', () => {
  beforeEach(async () => {
    await i18n.changeLanguage('en');
  });

  it.each(ENGLISH)('returns %s unchanged', (text) => {
    expect(localizeServerText(text)).toBe(text);
  });

  it.each(UNKNOWN)('passes %s through', (text) => {
    expect(localizeServerText(text)).toBe(text);
  });
});

describe('localizeServerText in Chinese', () => {
  beforeEach(async () => {
    await i18n.changeLanguage('zh-CN');
  });
  afterEach(async () => {
    await i18n.changeLanguage('en');
  });

  it.each(CHINESE)('translates %s', (text, chinese) => {
    expect(localizeServerText(text)).toBe(chinese);
  });

  it.each(UNKNOWN)('passes %s through', (text) => {
    expect(localizeServerText(text)).toBe(text);
  });

  it('maps the message and the hint of an error envelope', () => {
    const out = localizeServerError({
      category: 'auth',
      message: 'Gate refused the API key.',
      hint: 'Check it in Settings.',
      retryable: false,
    });
    expect(out).toEqual({ category: 'auth', message: "Gate 拒绝了该 API 密钥。", hint: "请在设置中检查。", retryable: false });
  });

  it('leaves an absent hint absent', () => {
    expect(localizeServerError({ message: 'Already even.' })).toEqual({ message: "已经均衡。" });
  });

  it('does not throw on an envelope with no message', () => {
    expect(localizeServerText(undefined as unknown as string)).toBeUndefined();
  });
});
